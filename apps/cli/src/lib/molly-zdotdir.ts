import { existsSync, mkdirSync } from 'fs';
import path from 'path';
import { getMollyDataDir } from '@molly/shared/node/installation-profile';

import { getGhShimHostBinDir } from './gh-shim-script';
import {
  normalizeComparablePath,
  toSingleQuotedShellString,
  writeIfChanged,
} from './shell-file-utils';

const MOLLY_ZDOTDIR_PATH = path.join(getMollyDataDir(), 'zdotdir');

const buildInheritedSourceTarget = (
  filename: '.zshenv' | '.zprofile' | '.zshrc' | '.zlogin' | '.zlogout',
  inheritZdotdir: string | undefined,
  currentZdotdirPath: string
): string => {
  if (!inheritZdotdir) {
    return `$HOME/${filename}`;
  }

  if (normalizeComparablePath(inheritZdotdir) === normalizeComparablePath(currentZdotdirPath)) {
    return `$HOME/${filename}`;
  }

  return toSingleQuotedShellString(path.join(inheritZdotdir, filename));
};

const buildZshPassthroughSource = (
  filename: '.zshenv' | '.zshrc' | '.zlogin' | '.zlogout',
  inheritZdotdir: string | undefined,
  currentZdotdirPath: string
): string => {
  const inheritedTarget = buildInheritedSourceTarget(filename, inheritZdotdir, currentZdotdirPath);
  return `# Auto-generated by Molly for gh wrapper support.
if [ -f ${inheritedTarget} ]; then
  . ${inheritedTarget}
fi
`;
};

const buildZshenvSource = (
  inheritZdotdir: string | undefined,
  currentZdotdirPath: string
): string => buildZshPassthroughSource('.zshenv', inheritZdotdir, currentZdotdirPath);

const buildZprofileSource = (
  ghShimBinDir: string,
  inheritZdotdir: string | undefined,
  currentZdotdirPath: string
): string => {
  const inheritedTarget = buildInheritedSourceTarget(
    '.zprofile',
    inheritZdotdir,
    currentZdotdirPath
  );
  return `# Auto-generated by Molly for gh wrapper support.
if [ -f ${inheritedTarget} ]; then
  . ${inheritedTarget}
fi

export PATH=${toSingleQuotedShellString(ghShimBinDir)}:"$PATH"
`;
};

export const shouldInjectZdotdirForGhShim = (): boolean =>
  process.platform === 'darwin' && (existsSync('/bin/zsh') || existsSync('/usr/bin/zsh'));

export const ensureMollyZdotdirForGhShim = (inheritZdotdir?: string): string => {
  const zdotdirPath = MOLLY_ZDOTDIR_PATH;
  mkdirSync(zdotdirPath, { recursive: true });

  writeIfChanged(path.join(zdotdirPath, '.zshenv'), buildZshenvSource(inheritZdotdir, zdotdirPath));
  writeIfChanged(
    path.join(zdotdirPath, '.zprofile'),
    buildZprofileSource(getGhShimHostBinDir(), inheritZdotdir, zdotdirPath)
  );
  writeIfChanged(
    path.join(zdotdirPath, '.zshrc'),
    buildZshPassthroughSource('.zshrc', inheritZdotdir, zdotdirPath)
  );
  writeIfChanged(
    path.join(zdotdirPath, '.zlogin'),
    buildZshPassthroughSource('.zlogin', inheritZdotdir, zdotdirPath)
  );
  writeIfChanged(
    path.join(zdotdirPath, '.zlogout'),
    buildZshPassthroughSource('.zlogout', inheritZdotdir, zdotdirPath)
  );

  return zdotdirPath;
};
