// Regenerate the unmodified MIT upstream adapter. Normal builds are offline.
import { build } from '../../cli/node_modules/esbuild/lib/main.js'
import { writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { dirname, resolve, posix } from 'node:path'
import { fileURLToPath } from 'node:url'

const commit = '3fecd4f931666fecd1fbd7c214ce544409ead6e8'
const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/main/services/browser-cdp-upstream'
)
const base = `https://raw.githubusercontent.com/microsoft/vscode/${commit}/`
const files = new Map()
const licenseResponse = await fetch(base + 'LICENSE.txt')
if (!licenseResponse.ok) throw new Error('Pinned upstream license unavailable')
const license = await licenseResponse.text()
await writeFile(
  resolve(dirname(fileURLToPath(import.meta.url)), '../browser-cdp-NOTICE.txt'),
  `VS Code browser/CDP adapter, commit ${commit}\nSource: ${base}\n\n${license}`
)
const result = await build({
  stdin: {
    contents: `export { CDPBrowserProxy } from 'upstream:src/vs/platform/browserView/common/cdp/proxy.ts';
export { BrowserViewDebugger } from 'upstream:src/vs/platform/browserView/electron-main/browserViewDebugger.ts';
export { BrowserViewCDPTarget } from 'upstream:src/vs/platform/browserView/electron-main/browserViewCDPTarget.ts';`
  },
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  banner: {
    js: `/* eslint-disable */\n/*! Generated by scripts/sync-browser-cdp.mjs; DO NOT EDIT.\nVS Code ${commit}\n${license}\n*/`
  },
  plugins: [
    {
      name: 'pinned-upstream',
      setup(builder) {
        builder.onResolve({ filter: /^upstream:/ }, (args) => ({
          path: args.path.slice(9),
          namespace: 'upstream'
        }))
        builder.onResolve({ filter: /^\./, namespace: 'upstream' }, (args) => ({
          path: posix
            .normalize(posix.join(posix.dirname(args.importer), args.path))
            .replace(/\.js$/, '.ts'),
          namespace: 'upstream'
        }))
        builder.onLoad({ filter: /.*/, namespace: 'upstream' }, async (args) => {
          const response = await fetch(base + args.path)
          if (!response.ok) throw new Error(`Cannot read pinned source ${args.path}`)
          const contents = await response.text()
          files.set(args.path, createHash('sha256').update(contents).digest('hex'))
          return { contents, loader: 'ts' }
        })
      }
    }
  ]
})
await writeFile(output + '.js', result.outputFiles[0].text)
await writeFile(
  output + '.sources.json',
  JSON.stringify(
    { commit, license: 'MIT', source: base, files: Object.fromEntries([...files].sort()) },
    null,
    2
  ) + '\n'
)
console.log(`Generated adapter from ${files.size} unchanged upstream files`)
