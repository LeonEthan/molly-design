import { readFile, readdir, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

// SVG files are the editable source. This small, deliberately restricted grammar
// keeps both renderers on the same geometry without a runtime XML parser.
const source = new URL('../src/ui-icons/svg/', import.meta.url);
const output = new URL('../src/ui-icons/generated.ts', import.meta.url);
const root =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">';
const allowed = new Set([
  'd',
  'x',
  'y',
  'x1',
  'y1',
  'x2',
  'y2',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'width',
  'height',
  'points',
  'opacity',
]);
const files = (await readdir(source)).filter((file) => file.endsWith('.svg')).sort();
const definitions = [];
for (const file of files) {
  const name = file.slice(0, -4);
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Invalid glyph name: ${file}`);
  const svg = (await readFile(new URL(file, source), 'utf8')).trim();
  if (!svg.startsWith(root) || !svg.endsWith('</svg>'))
    throw new Error(`Unexpected SVG root: ${file}`);
  let body = svg.slice(root.length, -6).trim();
  const nodes = [];
  while (body) {
    const element = /^<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^<>]*?)\s*\/>/.exec(
      body
    );
    if (!element) throw new Error(`Unexpected SVG content: ${file}: ${body.slice(0, 80)}`);
    let attributes = element[2].trim();
    const props = {};
    while (attributes) {
      const attr = /^([a-z][a-z0-9-]*)="([^"<>&]*)"(?:\s+|$)/.exec(attributes);
      if (!attr || !allowed.has(attr[1]) || Object.hasOwn(props, attr[1]))
        throw new Error(`Invalid SVG attribute: ${file}: ${attributes}`);
      props[attr[1]] = attr[2];
      attributes = attributes.slice(attr[0].length);
    }
    nodes.push([element[1], props]);
    body = body.slice(element[0].length).trim();
  }
  if (!nodes.length) throw new Error(`Empty icon: ${file}`);
  definitions.push(
    `export const ${name[0].toLowerCase()}${name.slice(1)}Icon = ${JSON.stringify(nodes)} as const satisfies readonly UiIconNode[];`
  );
}
const unformatted = `// Generated by scripts/generate-ui-icons.mjs. Edit svg/*.svg, then run pnpm icons:generate.\nimport type { UiIconNode } from './types';\n\n${definitions.join('\n\n')}\n`;
const code = await format(unformatted, {
  parser: 'typescript',
  singleQuote: true,
  printWidth: 100,
});
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== code)
    throw new Error('UI icon geometry is stale; run pnpm --filter @molly/shared icons:generate');
  console.log(`${files.length} SVG sources match generated geometry`);
} else {
  await writeFile(output, code);
  console.log(`Generated ${files.length} UI icons`);
}
