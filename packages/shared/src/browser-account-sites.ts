export type BrowserAccountSiteId = (typeof BROWSER_ACCOUNT_SITES)[number]['id'];
export const BROWSER_ACCOUNT_SITE_IDS = BROWSER_ACCOUNT_SITES.map((site) => site.id);

export function browserAccountSiteForDomain(domain: string) {
  const host = domain.replace(/^\./, '').toLowerCase();
  return BROWSER_ACCOUNT_SITES.find((site) =>
    site.domains.some((root) => host === root || host.endsWith(`.${root}`))
  );
}
